// Regenerates prototypes/<name>/src/version.generated.ts for every prototype
// that has a version.json. Reads the current committed counter (never
// increments it - that is scripts/bump-version.js's job) and stamps today's
// date fresh, so the version string always reflects "counter as of last
// deploy" + "date this build was made". Runs on every vite build/dev via
// vite.config.ts, and via the pretypecheck npm hook so `tsc --noEmit` (which
// never executes vite.config.ts) still has a file to import.
import { existsSync, readdirSync, readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

function formatDate(date) {
  const dd = String(date.getUTCDate()).padStart(2, '0');
  const mm = String(date.getUTCMonth() + 1).padStart(2, '0');
  const yy = String(date.getUTCFullYear() % 100).padStart(2, '0');
  return `${dd}${mm}${yy}`;
}

export function generateVersionStamps(rootDir) {
  const protoDir = path.join(rootDir, 'prototypes');
  if (!existsSync(protoDir)) return;

  for (const name of readdirSync(protoDir)) {
    const versionFile = path.join(protoDir, name, 'version.json');
    if (!existsSync(versionFile)) continue;

    const { counter } = JSON.parse(readFileSync(versionFile, 'utf8'));
    const stamp = `${formatDate(new Date())}r${String(counter).padStart(4, '0')}`;

    const srcDir = path.join(protoDir, name, 'src');
    mkdirSync(srcDir, { recursive: true });
    writeFileSync(
      path.join(srcDir, 'version.generated.ts'),
      `// Auto-generated by scripts/generate-versions.js. Do not edit by hand.\nexport const VERSION_STAMP = ${JSON.stringify(stamp)};\n`,
    );
  }
}

const isMain = process.argv[1] && import.meta.url === `file://${process.argv[1]}`;
if (isMain) {
  const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  generateVersionStamps(rootDir);
}
